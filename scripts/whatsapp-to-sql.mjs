#!/usr/bin/env node
/**
 * One-off: turn a WhatsApp leak log into idempotent SQL for the bladder diary.
 * Uses the same parser as the in-app importer (src/modules/bladder/whatsapp.ts).
 *
 *   node scripts/whatsapp-to-sql.mjs <chat.txt> --person "Kari" [--year 2026] [--tz Asia/Kolkata] > leaks.sql
 *
 * The SQL finds the person by display name (must match exactly one profile),
 * and skips rows that already exist (same person, minute and note), so it is
 * safe to run twice or after using the importer. A per-day summary goes to stderr.
 * Don't commit the chat or the generated SQL: it is personal health data.
 */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createJiti } from "jiti";

const root = fileURLToPath(new URL("..", import.meta.url));
const jiti = createJiti(import.meta.url, { alias: { "@/": `${root}src/` } });
const { parseWhatsAppLeaks } = await jiti.import(`${root}src/modules/bladder/whatsapp.ts`);

const args = process.argv.slice(2);
const flag = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : fallback;
};
const file = args.find((a, i) => !a.startsWith("--") && !args[i - 1]?.startsWith("--"));
if (!file) {
  console.error('Usage: node scripts/whatsapp-to-sql.mjs <chat.txt> --person "Kari" [--year 2026] [--tz Asia/Kolkata]');
  process.exit(1);
}
const person = flag("person", "");
if (!person) {
  console.error("--person is required (the diary owner's display name, e.g. Kari)");
  process.exit(1);
}
const tz = flag("tz", "Asia/Kolkata");
const year = flag("year") ? Number(flag("year")) : undefined;
const today = new Date().toLocaleDateString("en-CA", { timeZone: tz });

const { rows, skipped } = parseWhatsAppLeaks(readFileSync(file, "utf8"), { today, tz, year, ownerName: person });
if (!rows.length) {
  console.error("No leaks found.");
  process.exit(1);
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const offset = (iso) => {
  // Show the time as local time with its offset, so the SQL is easy to read.
  const d = new Date(iso);
  const parts = Object.fromEntries(new Intl.DateTimeFormat("en-CA", { timeZone: tz, year: "numeric", month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit", hourCycle: "h23" }).formatToParts(d).map((p) => [p.type, p.value]));
  const local = Date.UTC(+parts.year, +parts.month - 1, +parts.day, +parts.hour, +parts.minute);
  const mins = Math.round((local - d.getTime()) / 60000);
  const sign = mins >= 0 ? "+" : "-";
  const a = Math.abs(mins);
  return `${parts.year}-${parts.month}-${parts.day} ${parts.hour}:${parts.minute}:00${sign}${String(Math.floor(a / 60)).padStart(2, "0")}:${String(a % 60).padStart(2, "0")}`;
};

const values = rows.map((r) => `    (${q(offset(r.at))}::timestamptz, ${q(r.amount)}, ${r.triggers.length ? `array[${r.triggers.map(q).join(", ")}]::text[]` : "'{}'::text[]"}, ${q(r.notes)})`);

const out = `-- WhatsApp leak log for ${person}: ${rows.length} leaks, ${rows[0].date} to ${rows.at(-1).date}.
-- Generated by scripts/whatsapp-to-sql.mjs. Safe to run more than once.
do $$
declare
  v_owner uuid;
  v_household uuid;
  v_matches int;
  v_added int;
begin
  select count(*) into v_matches from public.profiles where display_name ilike ${q(`${person}%`)};
  if v_matches <> 1 then
    raise exception 'Expected exactly one profile whose name starts with "%", found %', ${q(person)}, v_matches;
  end if;
  select id into v_owner from public.profiles where display_name ilike ${q(`${person}%`)};

  select coalesce(
    (select p.active_household_id from public.profiles p
       join public.household_members m on m.household_id = p.active_household_id and m.user_id = p.id
      where p.id = v_owner),
    (select household_id from public.household_members where user_id = v_owner order by joined_at limit 1)
  ) into v_household;
  if v_household is null then
    raise exception 'No household found for %', ${q(person)};
  end if;

  with src(occurred_at, amount, triggers, notes) as (values
${values.join(",\n")}
  ), ins as (
    insert into public.bladder_events (household_id, owner_id, created_by, kind, occurred_at, amount, triggers, notes)
    select v_household, v_owner, v_owner, 'leak', s.occurred_at, s.amount, s.triggers, s.notes
      from src s
     where not exists (
       select 1 from public.bladder_events e
        where e.owner_id = v_owner
          and date_trunc('minute', e.occurred_at) = date_trunc('minute', s.occurred_at)
          and coalesce(e.notes, '') = s.notes
     )
    returning 1
  )
  select count(*) into v_added from ins;

  raise notice 'Added % of % leaks for % (the rest were already there).', v_added, ${rows.length}, ${q(person)};
end $$;
`;
process.stdout.write(out);

const perDay = new Map();
for (const r of rows) {
  const d = perDay.get(r.date) ?? { n: 0, drops: 0, small: 0, large: 0 };
  d.n++;
  d[r.amount]++;
  perDay.set(r.date, d);
}
console.error(`\n${rows.length} leaks over ${perDay.size} days. Skipped ${skipped.length} lines.\n`);
console.error("date        leaks  drops small large");
for (const [date, d] of perDay) console.error(`${date}  ${String(d.n).padStart(5)}  ${String(d.drops).padStart(5)} ${String(d.small).padStart(5)} ${String(d.large).padStart(5)}`);
const reasons = skipped.filter((s) => s.reason !== "Not a chat message line");
if (reasons.length) {
  console.error("\nSkipped:");
  for (const s of reasons) console.error(`  ${s.reason.padEnd(32)} ${s.line}`);
}
